"""Write the README's results section and MODEL_CARD.md from models/metadata.json.

Run from the project root after training:
    python -m src.report

Everything between the RESULTS markers in README.md is replaced, and MODEL_CARD.md
is rewritten whole, so every number in them comes from the saved training results
(and the gate/drift settings from src/config.py), never typed by hand.
"""
import json

from src import config
from src.config import METADATA_PATH, PROJECT_ROOT

README = PROJECT_ROOT / "README.md"
MODEL_CARD = PROJECT_ROOT / "MODEL_CARD.md"
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
NICE = {"lightgbm": "LightGBM", "hist_gradient_boosting": "HistGradientBoosting", "lasso": "Lasso", "ridge": "Ridge"}


def eur(x):
    return f"€{x:,.0f}"


def pct(x, d=1):
    return f"{x:.{d}f}%"


def results_markdown(m: dict) -> str:
    t, tl, d, r = m["test_metrics"], m["test_metrics_linear"], m["data"], m["range"]
    out = [
        "*Generated by `python -m src.report` from `models/metadata.json` "
        f"(model trained {m['trained_at'][:10]}). Do not edit by hand.*",
        "",
        f"Data: {d['raw_rows']:,} listings → {d['exact_duplicates']:,} exact duplicates removed → "
        f"{d['clean_rows']:,} rows; split {m['split']['train_rows']:,} train / {m['split']['test_rows']:,} test "
        f"(seed {m['split']['random_state']}).",
        "",
        "### Test set (used once, at the end)",
        "",
        "| | Linear (v1) | LightGBM (v2) |",
        "|---|---|---|",
        f"| Average % error (MAPE) | {pct(tl['mape_pct'])} | **{pct(t['mape_pct'])}** |",
        f"| Median % error | {pct(tl['median_ape_pct'])} | {pct(t['median_ape_pct'])} |",
        f"| Average error (€) | {eur(tl['mae_eur'])} | {eur(t['mae_eur'])} |",
        f"| R² | {tl['r2']:.3f} | {t['r2']:.3f} |",
        "",
        f"LightGBM's average error is **{(1 - t['mape_pct'] / tl['mape_pct']) * 100:.0f}% lower** than the linear model's.",
        "",
        "### Model comparison (5-fold cross-validation, training rows only)",
        "",
        "| Model | CV MAPE | ± fold std | CV MAE | CV R² | Tuning time |",
        "|---|---|---|---|---|---|",
    ]
    for row in m["cv_comparison"]:
        out.append(
            f"| {NICE.get(row['model'], row['model'])} | {pct(row['cv_mape_pct'], 2)} | {row['cv_mape_std']:.2f} | "
            f"{eur(row['cv_mae_eur'])} | {row['cv_r2']:.3f} | {row['search_minutes']:.1f} min |"
        )
    out += ["", f"Selected: **{NICE[m['selected_model']]}**. Rule (fixed before tuning):", "", "```", m["selection_rule"], "```", ""]

    out += [
        "### Errors by price band: before (linear) → after (LightGBM)",
        "",
        "Bands are quintiles of training prices, grouped by **real** price. Bias = median of (predicted − real) / real.",
        "",
        "| Real price | CV error, linear → LightGBM | Test error, linear → LightGBM | Test bias, linear → LightGBM |",
        "|---|---|---|---|",
    ]
    cvl = {x["band"]: x for x in m["cv_errors_by_band"]["linear"]}
    cvb = {x["band"]: x for x in m["cv_errors_by_band"]["boosting"]}
    tsl = {x["band"]: x for x in m["test_errors_by_band"]["linear"]}
    tsb = {x["band"]: x for x in m["test_errors_by_band"]["boosting"]}
    for b in m["band_labels"]:
        out.append(
            f"| {b} | {pct(cvl[b]['mape_pct'])} → {pct(cvb[b]['mape_pct'])} | "
            f"{pct(tsl[b]['mape_pct'])} → {pct(tsb[b]['mape_pct'])} | "
            f"{tsl[b]['median_bias_pct']:+.1f}% → {tsb[b]['median_bias_pct']:+.1f}% |"
        )
    te = m["test_top_end"]
    out += [
        "",
        f"Most expensive cars (real price over {eur(te['threshold_eur'])}, {te['n']} test cars): median bias "
        f"{te['linear']['median_bias_pct']:+.1f}% → {te['boosting']['median_bias_pct']:+.1f}%; still under-estimated in "
        f"{te['boosting']['share_under_estimated']:.0%} of cases (linear: {te['linear']['share_under_estimated']:.0%}). "
        "**Improved, not solved.**",
        "",
        "![Average % error by price decile, linear vs LightGBM](reports/figures/error_by_decile.png)",
        "",
        "### Price ranges (target: 80% of real prices inside)",
        "",
        f"Raw 10%/90% quantile models alone (out-of-fold, training rows): {r['oof_raw_coverage'][0]['by_estimate']:.1%} coverage, "
        "too narrow. After per-band conformal calibration, on the test set:",
        "",
        "| Band | Coverage, by estimated price | Coverage, by real price | Average range width |",
        "|---|---|---|---|",
    ]
    for row in m["test_range_coverage"]:
        name = "**All cars**" if row["band"] == "all" else row["band"]
        out.append(f"| {name} | {row['by_estimate']:.1%} | {row['by_actual']:.1%} | {pct(row['mean_width_pct'])} of estimate |")
    rules = m["rules"]
    out += [
        "",
        "The app groups by estimated price (the only price it knows), which is what the calibration targets.",
        "",
        f"High-price warning: shown above {eur(rules['high_price_threshold'])} (75th percentile of training prices), "
        f"because ranges there are wider on average ({pct(rules['oof_mean_width_pct']['high'])} vs "
        f"{pct(rules['oof_mean_width_pct']['normal'])}, out-of-fold).",
        "",
        "### Data facts behind the cleaning decisions",
        "",
        f"- Price skew {d['price_skew']:.2f} → {d['log_price_skew']:.2f} after log1p.",
        f"- {d['fractional_km_rows']:,} km values are fractional; the most common: "
        + ", ".join(f"{k} km ({v:,} row{'s' if v != 1 else ''})" for k, v in d["fractional_km_top_values"].items())
        + ". These are filled-in averages, not odometer readings.",
        f"- All cars are {d['age_range'][0]}–{d['age_range'][1]} years old.",
        "",
        f"Model file: {m['model_file_kb'] / 1024:.1f} MB (three LightGBM models). "
        f"Library versions: scikit-learn {m['versions']['sklearn']}, LightGBM {m['versions']['lightgbm']}.",
        "",
        "Full details, intended use and limits: [MODEL_CARD.md](MODEL_CARD.md).",
    ]
    return "\n".join(out)


def model_card_markdown(m: dict) -> str:
    """A model card: what the model is, what it is for, how well it works, and where it does not."""
    t, tl, d, r = m["test_metrics"], m["test_metrics_linear"], m["data"], m["rules"]
    cov = m["test_range_coverage"]
    te = m["test_top_end"]
    app = m["app"]
    cats = app["categories"]
    tuned = next(row for row in m["cv_comparison"] if row["model"] == m["selected_model"])
    params = ", ".join(f"{k}={v}" for k, v in sorted(json.loads(tuned["best_params"]).items()))
    gate_lo, gate_hi = config.GATE_COVERAGE_RANGE
    tsb = {x["band"]: x for x in m["test_errors_by_band"]["boosting"]}
    models = sorted(app["defaults"])
    brands = sorted({name.split()[0] for name in models})
    lo_age, hi_age = d["age_range"]
    minutes = f"about {round(m['training_minutes'])} minutes" if "training_minutes" in m else "a few minutes"
    out = [
        "# Model card: Used Car Pricing Engine",
        "",
        "*Generated by `python -m src.report` from `models/metadata.json` and `src/config.py`. Do not edit by hand.*",
        "",
        "## Model details",
        "",
        f"- **What it is:** a {NICE[m['selected_model']]} gradient-boosting model that estimates a used car's "
        "**listing (asking) price** in euros, with a likely price range and per-car explanations.",
        f"- **Version:** trained {m['trained_at'][:10]} ({m['training_mode']}), on `{m['data_file']['name']}` "
        f"(SHA-256 `{m['data_file']['sha256'][:12]}…`).",
        f"- **Parts:** one point model on log(price) with price allowed only to fall as km or age rise; "
        f"two quantile models ({int(m['range']['quantiles'][0] * 100)}th and {int(m['range']['quantiles'][1] * 100)}th "
        "percentile) for the range, calibrated with conformal correction per price band; SHAP values from LightGBM for explanations.",
        f"- **Settings:** {params}.",
        f"- **Libraries:** scikit-learn {m['versions']['sklearn']}, LightGBM {m['versions']['lightgbm']}, Python 3.12.",
        "- **Author:** Kaushik Yeddanapudi. **Code licence:** MIT (the dataset is not covered and not included).",
        "",
        "## Intended use",
        "",
        "- Estimating a fair listing price for a used car of a supported model, and checking whether an asking price "
        "is below, inside or above the likely range.",
        "- A learning and portfolio project: a guide to a market price, not a valuation for lending, insurance or legal purposes.",
        "",
        "**Out of scope** (the API rejects these instead of guessing): models other than "
        f"{', '.join(models)}; cars older than {hi_age} years; "
        "values outside the ranges seen in training. The model knows nothing about accidents, condition or service history.",
        "",
        "## Training data",
        "",
        f"- {d['raw_rows']:,} AutoScout24 listings provided by the upGrad / IIIT Bangalore course; "
        f"{d['exact_duplicates']:,} exact duplicates removed before splitting, leaving {d['clean_rows']:,}.",
        f"- Split: {m['split']['train_rows']:,} training and {m['split']['test_rows']:,} test listings "
        f"(random, seed {m['split']['random_state']}). The test set was scored once, after model selection.",
        f"- Fuel types: {', '.join(cats['Fuel'])}; gearboxes: {', '.join(cats['Gearing_Type'])}; "
        f"ages {lo_age}–{hi_age} years.",
        f"- Data quirks handled: {d['fractional_km_rows']:,} filled-in km values (fractional averages) refilled with the "
        "median real km of the same listing type; rare categories pooled; equipment lists turned into 0/1 flags.",
        "",
        "## Performance (test set)",
        "",
        "| | Linear baseline (v1) | This model |",
        "|---|---|---|",
        f"| Average % error (MAPE) | {pct(tl['mape_pct'])} | **{pct(t['mape_pct'])}** |",
        f"| Median % error | {pct(tl['median_ape_pct'])} | {pct(t['median_ape_pct'])} |",
        f"| Average error (€) | {eur(tl['mae_eur'])} | {eur(t['mae_eur'])} |",
        f"| R² | {tl['r2']:.3f} | {t['r2']:.3f} |",
        "",
        "| Real price band | Average % error | Median bias | Range coverage (by estimate) |",
        "|---|---|---|---|",
    ]
    covb = {x["band"]: x for x in cov[1:]}
    for b in m["band_labels"]:
        out.append(f"| {b} | {pct(tsb[b]['mape_pct'])} | {tsb[b]['median_bias_pct']:+.1f}% | {covb[b]['by_estimate']:.1%} |")
    out += [
        "",
        f"Price ranges contain the real price for **{cov[0]['by_estimate']:.1%}** of test cars (target "
        f"{r['range_coverage_target']:.0%}); average width {pct(cov[0]['mean_width_pct'])} of the estimate.",
        "",
        "## Limitations",
        "",
        f"- **Expensive cars:** for the {te['n']} test cars above {eur(te['threshold_eur'])}, the median bias is "
        f"{te['boosting']['median_bias_pct']:+.1f}% and {te['boosting']['share_under_estimated']:.0%} are under-estimated. "
        f"Ranges are wider above {eur(r['high_price_threshold'])}, and the app warns there.",
        f"- **Narrow coverage:** {len(models)} models from {len(brands)} brands ({', '.join(brands)}), ages {lo_age}–{hi_age} "
        "years, one marketplace; it will not generalise to other markets.",
        "- **Listing, not sale, price:** asking prices can differ from what cars actually sell for.",
        "- **Explanations describe the model, not the market:** SHAP effects say why the model gave a price, not what causes prices.",
        "",
        "## Monitoring and retraining",
        "",
        f"- **Drift check** (`python -m src.drift`): retraining is recommended when the median price moves more than "
        f"{config.PRICE_MEDIAN_SHIFT_PCT:g}%, a feature's PSI exceeds {config.PSI_SHIFT}, or more than "
        f"{config.OUT_OF_RANGE_SHARE:.0%} of rows are outside the training range.",
        f"- **Promotion gate** (`python -m src.retrain`): a challenger replaces this model only if its MAPE is at least "
        f"{config.GATE_MIN_IMPROVEMENT_PP} points lower and its ranges cover {gate_lo:.0%}–{gate_hi:.0%} of real prices, "
        f"on at least {config.GATE_MIN_EVAL_ROWS} rows that neither model was trained on. Decisions are logged in "
        "`models/promotion_log.jsonl` and MLflow.",
        "",
        "## Reproduce",
        "",
        f"Put the course CSV in `data/`, then `python -m src.train` ({minutes} for the last run) and `python -m src.report`. "
        "Training is deterministic: the same data and settings give the same model.",
    ]
    return "\n".join(out) + "\n"


def main():
    meta = json.loads(METADATA_PATH.read_text())
    text = README.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise SystemExit(f"README.md needs the markers {START} and {END}")
    before, rest = text.split(START, 1)
    _, after = rest.split(END, 1)
    README.write_text(before + START + "\n" + results_markdown(meta) + "\n" + END + after, encoding="utf-8")
    MODEL_CARD.write_text(model_card_markdown(meta), encoding="utf-8")
    print("README results section and MODEL_CARD.md updated from", METADATA_PATH.name)


if __name__ == "__main__":
    main()
